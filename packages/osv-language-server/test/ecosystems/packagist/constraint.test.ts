import { describe, it, expect } from "vitest";
import { composerLowerBound, rewriteComposerConstraint } from "../../../src/ecosystems/packagist/constraint.js";

describe("composerLowerBound", () => {
  it.each<[string, string | undefined]>([
    ["^7.0 || ^8.0", "7.0"],
    ["^8.0 | ^7.0", "7.0"],
    [">=7.4 <8", "7.4"],
    [">=7.4,<8", "7.4"],
    [">= 7.4, < 8", "7.4"],
    [">=7.0 >=7.2", "7.2"],
    ["~7.4.1", "7.4.1"],
    ["7.4.3", "7.4.3"],
    ["v1.2", "1.2"],
    ["1.2.*", "1.2.0"],
    ["2.*", "2.0"],
    ["1.0 - 2.0", "1.0"],
    ["^7.0@dev", "7.0"],
    ["*", undefined],
    ["dev-main", undefined],
    ["dev-*", undefined],
    ["<8", undefined],
    ["<=8 !=7.5", undefined],
    ["<8 || ^9.0", undefined],
    ["dev-main || ^2.0", "2.0"],
  ])("%s -> %s", (c, expected) => {
    expect(composerLowerBound(c)).toBe(expected);
  });
});

describe("rewriteComposerConstraint", () => {
  it.each<[string, string, string, boolean]>([
    ["^7.4", "7.15.0", "^7.15", false],
    ["^7.4", "7.4.5", "^7.4.5", false],
    ["^7.4.1", "7.4.5", "^7.4.5", false],
    ["^7.4", "8.1.0", "^8.1", true],
    ["^0.3", "0.3.5", "^0.3.5", false],
    ["^0.0", "0.0.5", "^0.0 >=0.0.5", false],
    ["~7.4", "7.15.0", "~7.15", false],
    ["~7.4", "7.4.5", "~7.4 >=7.4.5", false],
    ["~7.4.1", "7.4.5", "~7.4.5", false],
    ["~7.4.1", "7.5.0", "~7.5.0", true],
    [">=7.4", "7.6.1", ">=7.6.1", false],
    ["7.4.0", "7.6.1", "7.6.1", false],
    ["=7.4.0", "7.6.1", "=7.6.1", false],
    [">7.4", "7.6.1", ">=7.6.1", false],
    [">7.4", "7.4", ">=7.4", true],
    ["*", "7.6.1", ">=7.6.1", false],
    ["<8", "7.6.1", "<8 >=7.6.1", false],
    ["<8", "9.0.0", ">=9.0.0", true],
    [">=7.4,<8", "7.6.1", ">=7.6.1, <8", false],
    [">=7.4 <8", "8.1.0", ">=8.1.0", true],
    ["^7.0 >=7.2", "7.4.5", "^7.4.5 >=7.4.5", false],
    ["7.4.*", "7.4.5", "7.4.* >=7.4.5", false],
    ["7.4.*", "7.5.0", "7.5.*", true],
    ["7.*", "7.0.0", "7.*", false],
    ["!=7.5", "7.5", ">=7.5", true],
    ["!=7.5", "7.6", "!=7.5 >=7.6", false],
    ["^7.4@dev", "7.6.0", "^7.6@dev", false],
    ["^6.5 || ^7.0", "7.4.5", "^7.4.5", true],
    ["^6.5 || ^7.0", "7.0.0", "^7.0", true],
    ["^6.5||^7.0", "7.4.5", "^7.4.5", true],
    ["^7.0 || ^8.0", "7.4.5", "^7.4.5 || ^8.0", false],
    ["^6.5 || ^8.0", "7.4.5", "^7.4.5 || ^8.0", true],
    ["^6.5 || ^7.0", "9.1.0", "^9.1", true],
    ["^7.0 || >=7.2", "7.4.5", "^7.4.5 || >=7.4.5", false],
    ["^8.0 || ^9.0", "7.4.5", "^7.4.5 || ^9.0", false],
    ["dev-main || ^7.0", "7.4.5", "dev-main || ^7.4.5", false],
    ["dev-main", "7.4.5", "dev-main", false],
    ["1.0 - 2.0", "1.5.0", "1.5.0 - 2.0", false],
    ["1.0 - 2.0", "2.5.0", ">=2.5.0", true],
    ["1.0 - 2.5.0", "2.5.0", "2.5.0 - 2.5.0", false],
    ["1.0 - 2.5.0", "2.6.0", ">=2.6.0", true],
  ])("%s + %s", (raw, target, spec, widened) => {
    expect(rewriteComposerConstraint(raw, target)).toEqual({ spec, widened });
  });
});
