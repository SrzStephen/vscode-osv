// Generates every file-pattern list from the ecosystem modules (single source of truth):
// vscode-osv activationEvents, the client's DOCUMENT_GLOBS, and the pre-commit hook's `files:`.
// `--check` writes nothing and exits 1 if any output would change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { allFileGlobs, preCommitFilesRegex } = await import(
  pathToFileURL(join(root, "packages/osv-language-server/src/ecosystems/index.ts")).href
);
const check = process.argv.includes("--check");
const globs = allFileGlobs();
const stale: string[] = [];

function read(rel: string): string {
  try {
    return readFileSync(join(root, rel), "utf8").replace(/\r\n/g, "\n");
  } catch {
    return ""; // a not-yet-generated file
  }
}

function emit(rel: string, next: string): void {
  if (read(rel) === next) return;
  stale.push(rel);
  if (!check) writeFileSync(join(root, rel), next);
}

// 1. activationEvents: replace the workspaceContains entries, keep the rest (onLanguage etc.).
const pkgRel = "packages/vscode-osv/package.json";
const pkg = JSON.parse(read(pkgRel));
const kept = pkg.activationEvents.filter((e: string) => !e.startsWith("workspaceContains:"));
pkg.activationEvents = [...globs.map((g: string) => `workspaceContains:**/${g}`), ...kept];
emit(pkgRel, `${JSON.stringify(pkg, null, 2)}\n`);

// 2. generated client module.
emit(
  "packages/vscode-osv/src/generated/patterns.ts",
  `// Generated by scripts/sync-patterns.ts from the ecosystem modules; do not edit.\nexport const DOCUMENT_GLOBS: string[] = ${JSON.stringify(globs, null, 2)};\n`,
);

// 3. pre-commit hook.
const hookRel = ".pre-commit-hooks.yaml";
emit(hookRel, read(hookRel).replace(/^(\s*files: ).*$/m, (_m: string, prefix: string) => `${prefix}${preCommitFilesRegex()}`));

if (stale.length > 0) {
  console.log(`${check ? "out of date" : "updated"}: ${stale.join(", ")}`);
  if (check) {
    console.error("Run `npm run sync-patterns` and commit the result.");
    process.exit(1);
  }
}
